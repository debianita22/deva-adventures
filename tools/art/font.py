H = 9


def glyph_sprite(rows):
    w = max(len(r) for r in rows)
    img = blank(w, H)
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c == '#':
                img[y, x, :3] = rgb('w')
                img[y, x, 3] = 255
    return img


def all_sprites():
    out = {}
    for ch, rows in G.items():
        img = glyph_sprite(rows)
        if ch == ' ':
            img[0, 0, 3] = 0   # an empty 3x9 box: packed as a sprite all the same
        out['fnt_%02x' % ord(ch)] = img
    return out


def render(text, scale=4):
    """Preview helper: text -> RGBA image."""
    ws = [max(len(r) for r in G.get(c, G['?'])) for c in text]
    w = sum(ws) + len(text) + 2
    img = np.zeros((H + 2, w, 4), np.uint8)
    img[..., :3] = (40, 24, 60)
    img[..., 3] = 255
    x = 1
    for c, gw in zip(text, ws):
        for y, r in enumerate(G.get(c, G['?'])):
            for i, p in enumerate(r):
                if p == '#':
                    img[y + 1, x + i, :3] = (255, 244, 250)
        x += gw + 1
    return np.kron(img, np.ones((scale, scale, 1), np.uint8))
